// Packs template/ plus the kit (as src/maple/) into grove/src/template-files.ts, so Grove can
// write a whole new app in one commit. Run by npm run check and before deploying Grove.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const skip = new Set(["node_modules", ".env", ".env.local", ".neon"]);

function walk(dir: string, out: string[] = []) {
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const p = join(dir, name);
    statSync(p).isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
}

export function templateFiles() {
  const files: Record<string, string> = {};
  for (const p of walk(join(root, "template"))) files[relative(join(root, "template"), p)] = readFileSync(p, "utf8");
  for (const name of readdirSync(join(root, "kit"))) files[`src/maple/${name}`] = readFileSync(join(root, "kit", name), "utf8");
  return Object.fromEntries(Object.entries(files).sort());
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = templateFiles();
  writeFileSync(
    join(root, "grove/src/template-files.ts"),
    `// Generated by scripts/bundle-template.ts from template/ and kit/. Don't edit.\nexport const TEMPLATE: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`,
  );
  console.log(`${Object.keys(files).length} template files: ${Object.keys(files).join(", ")}`);
}
